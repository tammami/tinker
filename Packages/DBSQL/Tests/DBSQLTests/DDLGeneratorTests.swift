import DBCore
import XCTest

@testable import DBSQL

/// The diff that drives the table designer (SPEC §15b.2).
///
/// Every test here asserts the exact statement text. The generator's whole job is to be
/// predictable, and a test that only checks "some statement was produced" would pass on
/// SQL no server accepts.
final class DDLGeneratorTests: XCTestCase {
    let pgTable = TableRef(database: "d", schema: "public", name: "customers")
    let myTable = TableRef(database: "d", schema: "d", name: "customers")

    func pg() -> DDLGenerator { DDLGenerator(dialect: .postgresql) }
    func my() -> DDLGenerator { DDLGenerator(dialect: .mysql) }

    /// A definition with one integer id and one text name.
    func base(
        _ table: TableRef, idColumn: ColumnDefinition, nameColumn: ColumnDefinition
    )
        -> TableDefinition
    {
        TableDefinition(ref: table, columns: [idColumn, nameColumn], primaryKey: ["id"])
    }

    // MARK: - Create

    func testCreateTablePostgres() {
        let definition = TableDefinition(
            ref: pgTable,
            columns: [
                ColumnDefinition(name: "id", type: "integer", isNullable: false, isAutoIncrement: true),
                ColumnDefinition(name: "name", type: "text", isNullable: false),
                ColumnDefinition(name: "tier", type: "text", defaultExpression: "'ok'"),
            ],
            primaryKey: ["id"]
        )
        let statements = pg().create(definition)
        XCTAssertEqual(statements.count, 1)
        XCTAssertEqual(statements[0].kind, .createTable)
        XCTAssertEqual(
            statements[0].sql,
            """
            CREATE TABLE "public"."customers" (
                "id" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                "name" text NOT NULL,
                "tier" text DEFAULT 'ok',
                PRIMARY KEY ("id")
            )
            """)
    }

    func testCreateTableMySQLCarriesItsOptionsAndComment() {
        let definition = TableDefinition(
            ref: myTable,
            comment: "people who buy things",
            columns: [
                ColumnDefinition(name: "id", type: "int", isNullable: false, isAutoIncrement: true)
            ],
            primaryKey: ["id"],
            options: TableOptions(engine: "InnoDB", characterSet: "utf8mb4", collation: "utf8mb4_0900_ai_ci")
        )
        let sql = my().create(definition)[0].sql
        XCTAssertTrue(sql.contains("`id` int NOT NULL AUTO_INCREMENT"), sql)
        XCTAssertTrue(sql.contains("PRIMARY KEY (`id`)"), sql)
        XCTAssertTrue(sql.contains("ENGINE = InnoDB"), sql)
        XCTAssertTrue(sql.contains("DEFAULT CHARSET = utf8mb4"), sql)
        XCTAssertTrue(sql.contains("COMMENT = 'people who buy things'"), sql)
    }

    func testCreateEmitsIndexesAndCommentsAfterTheTable() {
        let definition = TableDefinition(
            ref: pgTable,
            comment: "a table",
            columns: [ColumnDefinition(name: "name", type: "text", comment: "their name")],
            indexes: [IndexDefinition(name: "customers_name_idx", columns: [IndexColumn(name: "name")])]
        )
        let kinds = pg().create(definition).map(\.kind)
        XCTAssertEqual(kinds, [.createTable, .createIndex, .comment, .comment])
    }

    // MARK: - Columns

    func testAddingAColumn() {
        let id = ColumnDefinition(name: "id", type: "integer", isNullable: false)
        let name = ColumnDefinition(name: "name", type: "text")
        var edited = base(pgTable, idColumn: id, nameColumn: name)
        edited.columns.append(ColumnDefinition(name: "email", type: "text", isNullable: false))

        let statements = pg().alter(from: base(pgTable, idColumn: id, nameColumn: name), to: edited)
        XCTAssertEqual(statements.count, 1)
        XCTAssertEqual(statements[0].kind, .addColumn)
        XCTAssertEqual(
            statements[0].sql,
            #"ALTER TABLE "public"."customers" ADD COLUMN "email" text NOT NULL"#
        )
        XCTAssertFalse(statements[0].isDestructive)
    }

    func testDroppingAColumnIsMarkedDestructive() {
        let id = ColumnDefinition(name: "id", type: "integer", isNullable: false)
        let name = ColumnDefinition(name: "name", type: "text")
        var edited = base(pgTable, idColumn: id, nameColumn: name)
        edited.columns.removeAll { $0.id == name.id }

        let statements = pg().alter(from: base(pgTable, idColumn: id, nameColumn: name), to: edited)
        XCTAssertEqual(statements.count, 1)
        XCTAssertEqual(statements[0].kind, .dropColumn)
        XCTAssertTrue(statements[0].isDestructive, "dropping a column loses its data")
        XCTAssertEqual(
            statements[0].sql,
            #"ALTER TABLE "public"."customers" DROP COLUMN "name""#
        )
    }

