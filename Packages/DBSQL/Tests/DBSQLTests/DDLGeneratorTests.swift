    // MARK: - Ordering

    /// Constraints come off before the columns they sit on, and go back on afterwards.
    /// Any other order and the server refuses the change for its own reasons.
    func testStatementOrderDropsDependantsFirstAndRebuildsThemLast() {
        let id = ColumnDefinition(name: "id", type: "integer", isNullable: false)
        let name = ColumnDefinition(name: "name", type: "text")
        var current = base(pgTable, idColumn: id, nameColumn: name)
        current.indexes = [IndexDefinition(name: "n_idx", columns: [IndexColumn(name: "name")])]
        current.checks = [CheckDefinition(name: "c", expression: "id > 0")]
        current.foreignKeys = [
            ForeignKeyDefinition(
                name: "fk", columns: ["id"], referencedTable: pgTable, referencedColumns: ["id"]
            )
        ]

        var edited = current
        edited.columns[1].type = "varchar(50)"
        edited.indexes[0].isUnique = true
        edited.checks[0].expression = "id > 1"
        edited.foreignKeys[0].onDelete = .cascade
        edited.primaryKey = ["id", "name"]

        let kinds = pg().alter(from: current, to: edited).map(\.kind)
        XCTAssertEqual(
            kinds,
            [
                .dropForeignKey, .dropCheck, .dropIndex, .dropPrimaryKey,
                .alterColumn,
                .addPrimaryKey, .createIndex, .addCheck, .addForeignKey,
            ])
    }

